function buildCanyonGates() {
  const zCoords = [-2200, -1720, -1240, -760, -280, 200, 680, 1160, 1640, 2120];
  return zCoords.map((z, i) => {
    const x = canyonCenterX(z);
    const ground = Math.max(0, sampleTerrainHeight(x, z));
    const dz = 100;
    const dx = canyonCenterX(z + dz) - x;
    const heading = ((Math.atan2(dx, -dz) * 180) / Math.PI + 360) % 360;
    return {
      pos: [x, ground + 68 + (i % 2) * 16, z],
      headingDeg: heading,
      radius: 34,
      label: `CANYON-${String(i + 1).padStart(2, '0')}`,
    };
  });
}

